#!/usr/bin/env bash
# Wire Desk anti-loss auto-snapshot helper (spec #227).
# Stages safe files, checks for accidental secrets/large artifacts, creates a
# timestamped WIP commit/tag or bundle backup so progress is never lost.
set -euo pipefail

MSG_PREFIX="${MSG_PREFIX:-wip}"
TAG="${TAG:-}"
BUNDLE="${BUNDLE:-0}"

log() { echo "[$(date -Is)] [snapshot] $*"; }

# Secret scan guard: refuse to commit if .env or secret patterns are staged.
SECRET_PATTERNS='\.env(\.|$)|AKIA[0-9A-Z]{16}|ghp_[A-Za-z0-9]{36}|sk_live_[A-Za-z0-9]{24}|whsec_[A-Za-z0-9]{24}'
if git diff --cached --name-only | grep -Ei "$SECRET_PATTERNS" 2>/dev/null; then
  log "refusing: staged files match secret patterns"
  exit 1
fi

# Large artifact guard.
LARGE=$(git diff --cached --name-only | xargs -I{} sh -c 'test -f "{}" && stat -c "%s {}"' 2>/dev/null | awk '$1 > 1048576 {print}' | head -5)
if [ -n "$LARGE" ]; then
  log "refusing: large artifacts staged (>1MiB): $LARGE"
  exit 1
fi

git add -A \
  -- ':!*.db' ':!*.db-wal' ':!*.db-shm' ':!*.sqlite' ':!backups/*' ':!logs/*' ':!tmp/*' ':!node_modules/*' ':!target/*' ':!.env*' 2>/dev/null || git add -A

if [ -z "$(git diff --cached --name-only)" ]; then
  log "nothing to commit"
  exit 0
fi

TS=$(date +%Y%m%d-%H%M%S)
COMMIT_MSG="${MSG_PREFIX}-${TS}: auto-snapshot"
git commit -m "$COMMIT_MSG" -m "auto-generated by scripts/snapshot_git.sh" >/dev/null

if [ -n "$TAG" ]; then
  git tag "${TAG}-${TS}"
  log "tagged ${TAG}-${TS}"
fi

if [ "$BUNDLE" = "1" ]; then
  BUNDLE_FILE="/tmp/kilo2/wired-snapshot-${TS}.bundle"
  git bundle create "$BUNDLE_FILE" HEAD
  log "bundle created: $BUNDLE_FILE"
fi

log "committed: $COMMIT_MSG"
